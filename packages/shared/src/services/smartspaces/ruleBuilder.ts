  // Get operators for a specific field type
  static getOperatorsForField(fieldId: string): OperatorDefinition[] {
    const field = this.getAvailableFields().find(f => f.id === fieldId);
    if (!field) return [];

    const allOperators = this.getOperators();
    return allOperators.filter(op =>
      field.operators.includes(op.id) &&
      op.supportedTypes.includes(field.type)
    );
  }

  // Validate a rule
  static validateRule(rule: SmartSpaceRule): { valid: boolean; errors: string[] } {
    const errors: string[] = [];
    const field = this.getAvailableFields().find(f => f.id === rule.field);

    if (!field) {
      errors.push(`Unknown field: ${rule.field}`);
      return { valid: false, errors };
    }

    if (!field.operators.includes(rule.operator)) {
      errors.push(`Invalid operator "${rule.operator}" for field "${field.label}"`);
    }

    // Validate value based on field type
    switch (field.type) {
      case 'boolean':
        if (typeof rule.value !== 'boolean') {
          errors.push(`Field "${field.label}" requires a boolean value`);
        }
        break;

      case 'number':
        if (typeof rule.value !== 'number') {
          errors.push(`Field "${field.label}" requires a number value`);
        }
        break;

      case 'date':
        if (!(rule.value instanceof Date) && typeof rule.value !== 'string') {
          errors.push(`Field "${field.label}" requires a date value`);
        }
        break;

      case 'enum':
        if (field.options && !field.options.some(opt => opt.value === rule.value)) {
          errors.push(`Invalid value for field "${field.label}"`);
        }
        break;

      case 'string':
        if (typeof rule.value !== 'string') {
          errors.push(`Field "${field.label}" requires a string value`);
        }
        break;

      case 'array':
        if (rule.operator === 'contains' || rule.operator === 'not_contains') {
          if (typeof rule.value !== 'string') {
            errors.push(`Array operations require a string value to search for`);
          }
        }
        break;
    }

    return {
      valid: errors.length === 0,
      errors
    };
  }

  // Validate complete rules
  static validateRules(rules: SmartSpaceRules): { valid: boolean; errors: string[] } {
    const errors: string[] = [];

    if (!rules.conditions || rules.conditions.length === 0) {
      errors.push('At least one condition is required');
    }

    if (!['AND', 'OR'].includes(rules.logic)) {
      errors.push('Logic must be either "AND" or "OR"');
    }

    // Validate each condition
    rules.conditions?.forEach((condition, index) => {
      const validation = this.validateRule(condition);
      if (!validation.valid) {
        validation.errors.forEach(error => {
          errors.push(`Condition ${index + 1}: ${error}`);
        });
      }
    });

    return {
      valid: errors.length === 0,
      errors
    };
  }

  // Convert rules to human-readable description
  static rulesToDescription(rules: SmartSpaceRules): string {
    if (!rules.conditions || rules.conditions.length === 0) {
      return 'No conditions defined';
    }

    const conditions = rules.conditions.map(condition => {
      const field = this.getAvailableFields().find(f => f.id === condition.field);
      const operator = this.getOperators().find(op => op.id === condition.operator);

      if (!field || !operator) {
        return `Invalid condition: ${condition.field} ${condition.operator} ${condition.value}`;
      }

      let valueDisplay = condition.value;

      // Format value based on type
      if (field.type === 'enum' && field.options) {
        const option = field.options.find(opt => opt.value === condition.value);
        valueDisplay = option ? option.label : condition.value;
      } else if (field.type === 'date') {
        valueDisplay = new Date(condition.value).toLocaleDateString();
      } else if (field.type === 'boolean') {
        valueDisplay = condition.value ? 'Yes' : 'No';
      }

      return `${field.label} ${operator.label} "${valueDisplay}"`;
    });

    const logicWord = rules.logic === 'AND' ? 'and' : 'or';

    if (conditions.length === 1) {
      return conditions[0];
    } else if (conditions.length === 2) {
      return `${conditions[0]} ${logicWord} ${conditions[1]}`;
    } else {
      const lastCondition = conditions.pop();
      return `${conditions.join(', ')} ${logicWord} ${lastCondition}`;
    }
  }

