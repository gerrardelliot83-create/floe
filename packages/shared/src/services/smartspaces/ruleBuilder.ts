  // Create a rule from natural language (simple implementation)
  static createRuleFromDescription(description: string): SmartSpaceRule | null {
    const normalized = description.toLowerCase().trim();

    // Simple patterns - in a real implementation, this would be more sophisticated
    const patterns = [
      {
        pattern: /^type\s+(is|equals?)\s+(.+)$/,
        factory: (matches: string[]) => ({
          field: 'type',
          operator: 'equals' as const,
          value: matches[2].replace(/["']/g, '')
        })
      },
      {
        pattern: /^(title|content)\s+contains?\s+["'](.+)["']$/,
        factory: (matches: string[]) => ({
          field: matches[1] as any,
          operator: 'contains' as const,
          value: matches[2]
        })
      },
      {
        pattern: /^is\s+pinned$/,
        factory: () => ({
          field: 'is_pinned',
          operator: 'equals' as const,
          value: true
        })
      },
      {
        pattern: /^is\s+archived$/,
        factory: () => ({
          field: 'is_archived',
          operator: 'equals' as const,
          value: true
        })
      }
    ];

    for (const { pattern, factory } of patterns) {
      const match = normalized.match(pattern);
      if (match) {
        try {
          return factory(match);
        } catch (error) {
          console.error('Failed to create rule from pattern:', error);
        }
      }
    }

    return null;
  }

  // Export rules to JSON
  static exportRules(rules: SmartSpaceRules): string {
    return JSON.stringify(rules, null, 2);
  }

  // Import rules from JSON
  static importRules(json: string): { success: boolean; rules?: SmartSpaceRules; error?: string } {
    try {
      const rules = JSON.parse(json) as SmartSpaceRules;
      const validation = this.validateRules(rules);

      if (!validation.valid) {
        return {
          success: false,
          error: `Invalid rules: ${validation.errors.join(', ')}`
        };
      }

      return {
        success: true,
        rules
      };
    } catch (error) {
      return {
        success: false,
        error: `Invalid JSON: ${error instanceof Error ? error.message : 'Unknown error'}`
      };
    }
  }
